// Usage:  node build-photos.js "D:\UTEM GRADUATE\GRADUATION PHOTO"
//
// Reads the subfolders (COUSIN / FAMILY / FRIENDS), copies the photos AND videos
// into ./photos/<category>/ with clean lowercase names, and writes photos-list.js.
// If the optional "sharp" package is installed (npm i sharp), photos are also
// resized to max 1600px and compressed so the site loads fast.

const fs = require("fs");
const path = require("path");

const SRC = process.argv[2] || "photos-source";
const OUT = "photos";
const CATEGORY = {
  cousin: "cousins",
  cousins: "cousins",
  family: "family",
  friend: "friends",
  friends: "friends",
};
const IMAGE = /\.(jpe?g|png|webp|gif|avif)$/i;
const VIDEO = /\.(mp4|webm|m4v|mov)$/i;
const MB = 1024 * 1024;
const MAX_FILE = 95 * MB; // GitHub rejects files over 100 MB

let sharp = null;
try { sharp = require("sharp"); } catch { /* optional */ }

let captions = {};
if (fs.existsSync("captions.json")) {
  captions = JSON.parse(fs.readFileSync("captions.json", "utf8"));
}

(async () => {
  if (!fs.existsSync(SRC)) {
    console.error(`❌ Folder not found: ${SRC}`);
    process.exit(1);
  }
  console.log(sharp ? "✅ sharp found — photos will be resized" : "ℹ️  sharp not installed — photos will be copied as-is (run: npm i sharp)");

  const groups = {};
  const heic = [];
  const tooBig = [];
  const bigVideos = [];
  const movFiles = [];
  let totalBytes = 0;

  for (const d of fs.readdirSync(SRC, { withFileTypes: true })) {
    if (!d.isDirectory()) continue;
    const cat = CATEGORY[d.name.toLowerCase()];
    if (!cat) { console.log(`⏭️  Skipping folder "${d.name}" (not family/cousin/friends)`); continue; }

    const outDir = path.join(OUT, cat);
    fs.rmSync(outDir, { recursive: true, force: true });
    fs.mkdirSync(outDir, { recursive: true });

    const files = fs
      .readdirSync(path.join(SRC, d.name))
      .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));

    groups[cat] = groups[cat] || [];
    let n = groups[cat].length;
    let photoCount = 0;
    let videoCount = 0;

    for (const f of files) {
      const from = path.join(SRC, d.name, f);
      if (/\.(heic|heif)$/i.test(f)) { heic.push(`${d.name}/${f}`); continue; }

      const isVideo = VIDEO.test(f);
      const isImage = IMAGE.test(f);
      if (!isVideo && !isImage) continue;

      if (isVideo) {
        const size = fs.statSync(from).size;
        if (size > MAX_FILE) { tooBig.push(`${d.name}/${f} (${Math.round(size / MB)} MB)`); continue; }
        if (size > 40 * MB) bigVideos.push(`${d.name}/${f} (${Math.round(size / MB)} MB)`);
        if (/\.mov$/i.test(f)) movFiles.push(`${d.name}/${f}`);

        n++;
        const ext = path.extname(f).toLowerCase();
        const name = `${cat}-${String(n).padStart(3, "0")}${ext}`;
        const to = path.join(outDir, name);
        fs.copyFileSync(from, to);
        totalBytes += size;
        groups[cat].push({ type: "video", src: `photos/${cat}/${name}`, category: cat, caption: captions[name] || "" });
        videoCount++;
        continue;
      }

      n++;
      const isGif = /\.gif$/i.test(f);
      const ext = sharp && !isGif ? ".jpg" : path.extname(f).toLowerCase().replace(".jpeg", ".jpg");
      const name = `${cat}-${String(n).padStart(3, "0")}${ext}`;
      const to = path.join(outDir, name);

      if (sharp && !isGif) {
        await sharp(from)
          .rotate()
          .resize({ width: 1600, height: 1600, fit: "inside", withoutEnlargement: true })
          .jpeg({ quality: 82 })
          .toFile(to);
      } else {
        fs.copyFileSync(from, to);
      }
      totalBytes += fs.statSync(to).size;
      groups[cat].push({ type: "image", src: `photos/${cat}/${name}`, category: cat, caption: captions[name] || "" });
      photoCount++;
    }
    console.log(`📁 ${d.name} → ${cat}: ${photoCount} photos, ${videoCount} videos`);
  }

  // Mix the categories so "All" alternates family / cousins / friends
  const lists = Object.values(groups);
  const items = [];
  for (let i = 0; lists.some((l) => i < l.length); i++) {
    lists.forEach((l) => { if (i < l.length) items.push(l[i]); });
  }

  fs.writeFileSync("photos-list.js", `// Auto-generated by build-photos.js — do not edit by hand.\nconst PHOTOS = ${JSON.stringify(items, null, 2)};\n`);
  console.log(`\n🎓 Done! ${items.length} items written to photos-list.js (${Math.round(totalBytes / MB)} MB total)`);

  if (totalBytes > 900 * MB) {
    console.log("\n⚠️  Total size is over ~900 MB. GitHub recommends repos under 1 GB — consider shorter/compressed videos.");
  }
  if (tooBig.length) {
    console.log(`\n⚠️  ${tooBig.length} video(s) SKIPPED because they are over 95 MB (GitHub limit is 100 MB):`);
    tooBig.forEach((t) => console.log("   - " + t));
    console.log("   Compress them (e.g. with HandBrake, 720p/1080p MP4) and run this script again.");
  }
  if (bigVideos.length) {
    console.log(`\nℹ️  Large videos (they work, but load slowly): `);
    bigVideos.forEach((t) => console.log("   - " + t));
  }
  if (movFiles.length) {
    console.log(`\nℹ️  ${movFiles.length} .MOV file(s) found. If one doesn't play in the browser, convert it to MP4 (HandBrake is free).`);
  }
  if (heic.length) {
    console.log(`\n⚠️  ${heic.length} HEIC (iPhone) photos were skipped — browsers can't show them.`);
    console.log("   Export them as JPG first, then run this script again:");
    heic.slice(0, 10).forEach((h) => console.log("   - " + h));
  }
})();
